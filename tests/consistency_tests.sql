CREATE OR REPLACE TEMPORARY TABLE SC.OPS._AGENT_ANS AS
SELECT r.Q_ID, MAX(r.ERR) AS ERR,
       LISTAGG(IFF(c.VALUE:type = 'text', c.VALUE:text::VARCHAR, NULL), '') WITHIN GROUP (ORDER BY c.INDEX) AS TXT,
       ARRAY_AGG(DISTINCT IFF(c.VALUE:type = 'tool_use', c.VALUE:tool_use:name::VARCHAR, NULL)) AS TOOLS,
       COUNT_IF(c.VALUE:tool_use:input:sql::VARCHAR ILIKE '%SEMANTIC_VIEW(SC.SEMANTIC.SV_SUPPLY_CHAIN%') AS SV_SQL,
       COUNT_IF(REGEXP_LIKE(c.VALUE:tool_use:input::VARCHAR, '.*(CONFORMED|RAW_[A-Z]|LEGACY|FACT_|DIM_).*', 'is')) AS BAD_REFS,
