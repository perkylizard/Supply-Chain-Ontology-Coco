-- -----------------------------------------------------------------------------
-- F. RAW integrity summary (recurring data-quality check)
--    Orphans per FK, duplicate keys, date ranges, split shipments, POD date flips.
--    Real defects FAIL on any non-zero count. Planted issues PASS only while they
--    stay inside their planted band, so the demo data cannot drift silently.
-- -----------------------------------------------------------------------------
INSERT INTO SC.OPS._RESULTS
WITH
shp AS (
  SELECT * FROM SC.RAW_LOGISTICS.SHIPMENTS
  QUALIFY ROW_NUMBER() OVER (PARTITION BY SHIPMENT_ID ORDER BY LOADED_TS) = 1
),
xwalk AS (
  SELECT SUPPLIER_ID, SUPPLIER_PART_NO,
         'P' || LPAD(REGEXP_SUBSTR(SUPPLIER_PART_NO, '[0-9]+$'), 6, '0') AS ERP_PART_ID
  FROM SC.RAW_SUPPLIER.SUPPLIER_PARTS
),
-- N = orphans, DENOM = child rows, LO/HI = planted band in % (NULL = must be 0)
fk (CHK, N, DENOM, LO, HI) AS (
            SELECT 'SALES_ORDERS.CUSTOMER_ID->CUSTOMERS', COUNT_IF(y.CUSTOMER_ID IS NULL), COUNT(*), NULL::FLOAT, NULL::FLOAT
            FROM SC.RAW_ERP.SALES_ORDERS x LEFT JOIN SC.RAW_ERP.CUSTOMERS y ON y.CUSTOMER_ID = x.CUSTOMER_ID
  UNION ALL SELECT 'SALES_ORDERS.PLANT_ID->PLANTS', COUNT_IF(y.PLANT_ID IS NULL), COUNT(*), NULL, NULL
            FROM SC.RAW_ERP.SALES_ORDERS x LEFT JOIN SC.RAW_ERP.PLANTS y ON y.PLANT_ID = x.PLANT_ID
  UNION ALL SELECT 'ORDER_LINES.SO_ID->SALES_ORDERS', COUNT_IF(y.SO_ID IS NULL), COUNT(*), NULL, NULL
            FROM SC.RAW_ERP.ORDER_LINES x LEFT JOIN SC.RAW_ERP.SALES_ORDERS y ON y.SO_ID = x.SO_ID
  UNION ALL SELECT 'ORDER_LINES.PART_ID->PARTS', COUNT_IF(y.PART_ID IS NULL), COUNT(*), NULL, NULL
