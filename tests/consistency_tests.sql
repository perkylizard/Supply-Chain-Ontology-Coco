               ('USAGE', 'DATABASE', 'SNOWFLAKE'), ('PROGRAM USAGE', 'DATABASE', 'SNOWFLAKE')),
j AS (SELECT e.NAME AS E_NAME, g.NAME AS G_NAME, COALESCE(g.PRIVILEGE, e.PRIVILEGE) AS PRIVILEGE
