  FOR r IN c DO
    n := r.NAME;
    q := r.VAL;
    BEGIN
      EXECUTE IMMEDIATE :q;
      INSERT INTO SC.OPS._VQR_RUN VALUES (:n, NULL);
    EXCEPTION WHEN OTHER THEN
      INSERT INTO SC.OPS._VQR_RUN VALUES (:n, LEFT(:SQLERRM, 200));
    END;
  END FOR;
  RETURN 'ran';
END;
$$;
